export const ART_FALLBACK = 'shopping-cart';

/**
 * Class for an <Image> inside a frame: uploaded photos fill the whole frame
 * edge to edge (`photo-fill` in globals.css); the flat artwork keeps its own
 * centred, padded look because it is drawn with transparent margins.
 */
export const fitClass = (src: string | undefined, base: string): string =>
  src && !src.startsWith('/cat/') ? `${base} photo-fill` : base;

/** Public path of the flat artwork the backend asks for by name. */
export function artSrc(icon?: string | null): string {
  const key = icon && ART_KEYS.has(icon) ? icon : ART_FALLBACK;
  return `/cat/${key}.png`;
}
